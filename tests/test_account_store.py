def test_record_accepts_ciphertext_and_empty_credentials(aek_hex: str) -> None:
    record = encrypt_account_record(_account_payload(), aek_hex)
    assert is_ciphertext_field(record.password)
    assert record.smtp is not None and is_ciphertext_field(record.smtp.password)
    # An empty IMAP password is encrypted like upstream addAccount does; an
    # empty SMTP password stays empty ("no credential") like upstream writes.
    no_credentials = encrypt_account_record(
        _account_payload(
            password="",
            smtp={"host": "smtp.example.org", "port": 465, "secure": True, "password": ""},
        ),
        aek_hex,
    )
    assert is_ciphertext_field(no_credentials.password)
    assert decrypt_field(aek_hex, no_credentials.password) == ""
    assert no_credentials.smtp is not None and no_credentials.smtp.password == ""


