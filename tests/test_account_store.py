# --- account_count tracking and reconcile ----------------------------------


def test_put_account_syncs_the_stored_account_count(
    paths: Paths, user_id: str, aek_hex: str
) -> None:
    """Every insert (and every replace) leaves the counter at the real size."""
    assert _user_record(paths, user_id).account_count == 0

    first = _seed(paths, user_id, aek_hex)
    assert _user_record(paths, user_id).account_count == 1

    _seed(paths, user_id, aek_hex, name="Second")
    assert _user_record(paths, user_id).account_count == 2

    renamed = first.model_copy(update={"name": "Renamed"})
    put_account(paths, user_id, renamed)  # replace by explicit id
    assert _user_record(paths, user_id).account_count == 2  # unchanged


def test_delete_account_syncs_the_stored_account_count(
    paths: Paths, user_id: str, aek_hex: str
) -> None:
    """Deletes walk the counter back down; failures leave it untouched."""
    first = _seed(paths, user_id, aek_hex, name="First")
    second = _seed(paths, user_id, aek_hex, name="Second")
    assert _user_record(paths, user_id).account_count == 2

    delete_account(paths, user_id, first.id)
    assert _user_record(paths, user_id).account_count == 1

    delete_account(paths, user_id, second.id)
    assert _user_record(paths, user_id).account_count == 0

    # A failed delete (missing id) must not move the counter.
    with pytest.raises(FileNotFoundError):
        delete_account(paths, user_id, "never-existed")
    assert _user_record(paths, user_id).account_count == 0


def test_account_count_sync_skips_a_missing_user_record(paths: Paths) -> None:
    """put/delete against an unknown-but-valid id skip the counter quietly.

    The accounts file is already written when the sync runs — a user
    record that does not exist (out-of-band store tree) simply has no
    counter to update; the mutation itself must not fail.
    """
    ghost = os.urandom(16).hex()  # registry-valid shape, no user record
    stored = _seed(paths, ghost, _aek())

    assert get_user(paths, ghost) is None  # no counter was invented
    assert len(list_accounts(paths, ghost)) == 1

    delete_account(paths, ghost, stored.id)
    assert get_user(paths, ghost) is None
    assert list_accounts(paths, ghost) == []


def test_account_count_sync_isolates_users(paths: Paths, aek_hex: str) -> None:
    """One user's counter moves never touch another user's record."""
    alice, _ = create_user(paths, "alice")
    bob, _ = create_user(paths, "bob")

    stored = _seed(paths, alice.id, aek_hex)
    assert _user_record(paths, alice.id).account_count == 1
    assert _user_record(paths, bob.id).account_count == 0

    delete_account(paths, alice.id, stored.id)
    assert _user_record(paths, alice.id).account_count == 0
    assert _user_record(paths, bob.id).account_count == 0


def test_reconcile_account_count_repairs_a_stale_counter(
    paths: Paths, user_id: str, aek_hex: str
) -> None:
    """A stale stored count is corrected and persisted; a fresh one is not."""
    _seed(paths, user_id, aek_hex)
    stale = update_user(paths, user_id, {"account_count": 0})  # force the defect
    assert stale.account_count == 0

    repaired = reconcile_account_count(paths, stale)

    assert repaired.account_count == 1
    assert _user_record(paths, user_id).account_count == 1  # persisted
    # Already-fresh counters are returned untouched — no gratuitous write.
    assert reconcile_account_count(paths, repaired) is repaired


def test_reconcile_account_counts_repairs_every_user(
    paths: Paths, aek_hex: str
) -> None:
    """The plural reconcile fixes every stale counter and returns the views."""
    alice, _ = create_user(paths, "alice")
    bob, _ = create_user(paths, "bob")
    _seed(paths, alice.id, aek_hex, name="A1")
    _seed(paths, bob.id, aek_hex, name="B1")
    _seed(paths, bob.id, aek_hex, name="B2")
    update_user(paths, alice.id, {"account_count": 9})  # stale, overshoot
    update_user(paths, bob.id, {"account_count": 0})  # stale, undershoot

    views = reconcile_account_counts(paths)

    by_id = {view.id: view for view in views}
    assert by_id[alice.id].account_count == 1
    assert by_id[bob.id].account_count == 2
    assert _user_record(paths, alice.id).account_count == 1  # persisted
    assert _user_record(paths, bob.id).account_count == 2  # persisted


# --- reencrypt_all ---------------------------------------------------------------


def test_reencrypt_all_round_trips_every_credential_field(
    paths: Paths, user_id: str
) -> None:
    old_aek, new_aek = _aek(), _aek()
    with_smtp = _seed(paths, user_id, old_aek)
    without_smtp = _seed(paths, user_id, old_aek, name="Bare", smtp=None)

    reencrypt_all(paths, user_id, old_aek, new_aek)

    for stored in (with_smtp, without_smtp):
        loaded = get_account(paths, user_id, stored.id)
        assert loaded is not None
        assert loaded.password != stored.password  # re-encrypted
        assert loaded.decrypt_password(new_aek) == "correct horse battery staple"
        with pytest.raises(ValueError):
            loaded.decrypt_password(old_aek)  # old key no longer decrypts
    reloaded = get_account(paths, user_id, with_smtp.id)
    assert reloaded is not None
    assert reloaded.decrypt_smtp_password(new_aek) == "smtp-secret-9"
    bare_reloaded = get_account(paths, user_id, without_smtp.id)
    assert bare_reloaded is not None
    assert bare_reloaded.decrypt_smtp_password(new_aek) == ""
    store_file = _store_file(paths, user_id)
    assert _mode(store_file) == 0o600  # the atomic replace kept the mode


def test_reencrypt_all_is_a_noop_without_a_store(paths: Paths, user_id: str) -> None:
    reencrypt_all(paths, user_id, _aek(), _aek())
    assert not _store_file(paths, user_id).exists()  # nothing was created


