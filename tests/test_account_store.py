def test_materialize_key_file_writes_exact_hex_at_0600(
    paths: Paths, user_id: str, aek_hex: str
) -> None:
    key_path = materialize_key_file(paths, user_id, aek_hex)

    assert key_path == key_file_path(paths, user_id)
    assert key_path.read_bytes() == aek_hex.encode("ascii")  # no trailing newline
    assert _mode(key_path) == 0o600
    assert _mode(paths.user_imap_store_dir(user_id)) == 0o700


def test_materialize_key_file_rejects_bad_hex_without_writing(
    paths: Paths, user_id: str
) -> None:
    with pytest.raises(ValueError):
        materialize_key_file(paths, user_id, "not-hex")
    assert not paths.user_imap_store_dir(user_id).exists()


def test_cleanup_key_file_removes_and_is_idempotent(
    paths: Paths, user_id: str, aek_hex: str
) -> None:
    materialize_key_file(paths, user_id, aek_hex)
    assert key_file_path(paths, user_id).exists()

    cleanup_key_file(paths, user_id)
    assert not key_file_path(paths, user_id).exists()

    cleanup_key_file(paths, user_id)  # idempotent
    cleanup_key_file(paths, "user-without-store")  # and missing-safe
    assert not key_file_path(paths, "user-without-store").exists()


def test_orphan_sweep_deletes_only_orphaned_key_files(paths: Paths) -> None:
    crash_victim_a, crash_victim_b, clean_user = "user-a", "user-b", "user-c"
    for user in (crash_victim_a, crash_victim_b, clean_user):
        materialize_key_file(paths, user, _aek())
    cleanup_key_file(paths, clean_user)  # the well-behaved session ended
    keep_me = _store_file(paths, crash_victim_a)
    keep_me.write_text("[]", encoding="utf-8")
    stray = paths.users_dir() / "stray-file"
    stray.write_text("not a user directory", encoding="utf-8")

    swept = sweep_orphan_key_files(paths)

    assert swept == [crash_victim_a, crash_victim_b]  # sorted; clean user absent
    assert not key_file_path(paths, crash_victim_a).exists()
    assert not key_file_path(paths, crash_victim_b).exists()
    assert keep_me.read_text(encoding="utf-8") == "[]"  # store data untouched
    assert stray.exists()  # non-directory entries are left alone


def test_orphan_sweep_without_users_dir_is_empty(paths: Paths) -> None:
    assert sweep_orphan_key_files(paths) == []


