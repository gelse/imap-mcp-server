# --- upstream_format: the upstream byte format -----------------------------------


def test_encrypt_field_round_trips_representative_payloads(aek_hex: str) -> None:
    for plaintext in ("s3cret", "p@sswörd mit Unicode ✓", "line1\nline2", "x" * 10_000):
        sealed = encrypt_field(aek_hex, plaintext)
        assert decrypt_field(aek_hex, sealed) == plaintext


def test_encrypt_field_produces_upstream_iv_ciphertext_hex_shape(aek_hex: str) -> None:
    sealed = encrypt_field(aek_hex, _KAT_PLAINTEXT)
    iv_hex, ciphertext_hex = sealed.split(":")
    assert len(iv_hex) == 32  # a 16-byte IV, hex-encoded
    assert len(ciphertext_hex) % 32 == 0  # whole AES blocks
    assert re.fullmatch(r"[0-9a-f]+", iv_hex) is not None
    assert re.fullmatch(r"[0-9a-f]+", ciphertext_hex) is not None
    assert is_ciphertext_field(sealed)


def test_encrypt_field_uses_a_fresh_iv_per_field(aek_hex: str) -> None:
    first = encrypt_field(aek_hex, "same plaintext")
    second = encrypt_field(aek_hex, "same plaintext")
    assert first != second  # different IVs...
    assert first.split(":")[0] != second.split(":")[0]
    assert decrypt_field(aek_hex, second) == "same plaintext"  # ...same meaning


def test_decrypt_field_matches_node_known_answer_vector() -> None:
    """Ciphertext produced by Node's crypto (upstream's construction) decrypts."""
    assert decrypt_field(_KAT_KEY, _KAT_PASSWORD_CIPHERTEXT) == _KAT_PLAINTEXT


def test_decrypt_field_matches_node_vector_for_empty_plaintext() -> None:
    """An empty plaintext seals to a single PKCS7 padding block — as upstream."""
    assert decrypt_field(_KAT_KEY, _KAT_EMPTY_CIPHERTEXT) == ""
    assert decrypt_field(_KAT_KEY, encrypt_field(_KAT_KEY, "")) == ""


def test_decrypt_field_empty_value_means_no_credential(aek_hex: str) -> None:
    assert decrypt_field(aek_hex, "") == ""  # upstream decryptField semantics


@pytest.mark.parametrize(
    "case",
    ["missing-separator", "bad-iv-hex", "bad-ct-hex", "short-iv", "tampered-ct"],
)
def test_decrypt_field_fails_loud_on_malformed_values(aek_hex: str, case: str) -> None:
    sealed = encrypt_field(aek_hex, "s3cret")
    iv_hex, ct_hex = sealed.split(":")
    if case == "missing-separator":
        value = "not-an-encrypted-string"
    elif case == "bad-iv-hex":
        value = f"zz{iv_hex[2:]}:{ct_hex}"
    elif case == "bad-ct-hex":
        value = f"{iv_hex}:zz{ct_hex[2:]}"
    elif case == "short-iv":
        value = f"{iv_hex[:30]}:{ct_hex}"
    else:
        flipped = ("0" if ct_hex[0] != "0" else "1") + ct_hex[1:]
        value = f"{iv_hex}:{flipped}"
    with pytest.raises(ValueError):
        decrypt_field(aek_hex, value)


def test_decrypt_field_rejects_wrong_key(aek_hex: str) -> None:
    sealed = encrypt_field(aek_hex, "s3cret")
    with pytest.raises(ValueError):  # PKCS7 padding failure, never wrong bytes
        decrypt_field(_aek(), sealed)


def test_parse_aek_hex_accepts_only_32_bytes_of_hex() -> None:
    assert parse_aek_hex(_KAT_KEY) == bytes.fromhex(_KAT_KEY)
    with pytest.raises(ValueError, match="64 characters"):
        parse_aek_hex("ab" * 31)
    with pytest.raises(ValueError, match="64 characters"):
        parse_aek_hex("ab" * 33)
    with pytest.raises(ValueError, match="hexadecimal"):
        parse_aek_hex("zz" * 32)
    # bytes.fromhex silently skips ASCII whitespace: a spaced 64-char string
    # must not slip through as a short (or whitespace-containing) key.
    with pytest.raises(ValueError, match="32 raw bytes"):
        parse_aek_hex("ab" * 31 + "  ")


def test_is_ciphertext_field_rejects_non_cipher_shapes() -> None:
    assert is_ciphertext_field("plaintext-password") is False
    assert is_ciphertext_field("a:b") is False
    assert is_ciphertext_field("00:" + "ab" * 16) is False  # short IV hex
    assert is_ciphertext_field("0" * 32 + ":") is False  # empty ciphertext
    assert is_ciphertext_field(_KAT_PASSWORD_CIPHERTEXT) is True


