def test_rotate_aek_reencrypts_the_account_store(paths: Paths, user_id: str) -> None:
    """End-to-end: the import-time hook turns rotation into a real re-encrypt.

    Deliberately WITHOUT the ``reencrypt_registry`` fixture: the store must be
    a live rotation participant exactly as the app will run it.
    """
    ensure_wrap_key(paths)
    old_aek = activate_aek(paths, user_id)
    stored = _seed(paths, user_id, old_aek)
    raw_before = _store_file(paths, user_id).read_bytes()

    new_aek = rotate_aek(paths, user_id)

    loaded = get_account(paths, user_id, stored.id)
    assert loaded is not None
    assert loaded.password != stored.password  # the file changed
    assert loaded.decrypt_password(new_aek) == "correct horse battery staple"
    with pytest.raises(ValueError):
        loaded.decrypt_password(old_aek)
    assert new_aek not in _store_file(paths, user_id).read_text(encoding="utf-8")
    assert raw_before != _store_file(paths, user_id).read_bytes()


def test_registered_hook_is_a_noop_for_user_without_store(
    paths: Paths, user_id: str
) -> None:
    """Rotation before the first account exists must not create a store."""
    ensure_wrap_key(paths)
    activate_aek(paths, user_id)

    new_aek = rotate_aek(paths, user_id)

    assert HEX64_RE.fullmatch(new_aek)
    assert not _store_file(paths, user_id).exists()


def test_failing_hook_aborts_rotation_with_store_untouched(
    paths: Paths,
    user_id: str,
    aek_hex: str,
    reencrypt_registry: list[aek_rotation.ReencryptHook],
) -> None:
    ensure_wrap_key(paths)
    activate_aek(paths, user_id)
    stored = _seed(paths, user_id, aek_hex)
    raw_before = _store_file(paths, user_id).read_bytes()

    def failing_hook(paths: Paths, uid: str, old: str, new: str) -> None:
        raise RuntimeError("store re-encryption failed")

    reencrypt_registry.append(failing_hook)

    with pytest.raises(RuntimeError, match="re-encryption failed"):
        rotate_aek(paths, user_id)

    assert _store_file(paths, user_id).read_bytes() == raw_before
    loaded = get_account(paths, user_id, stored.id)
    assert loaded is not None
    assert loaded.decrypt_password(aek_hex) == "correct horse battery staple"


